// نرمال‌سازی متن فارسی برای جست‌وجوی هوشمندتر توی بانک سؤال.
// مشکل واقعی: خیلی از گوشی‌ها/کیبوردها به‌جای حروف فارسی (ک ی) از حروف عربی (ك ي) استفاده می‌کنن،
// نیم‌فاصله گاهی هست گاهی نیست («می‌شه» در برابر «میشه»)، و اعداد فارسی/عربی/لاتین قاطی می‌شن.
// این فایل یه نسخهٔ نرمال از متن (JS، برای خود search term) و یه SQL معادلش (برای ستون‌های جدول)
// می‌سازه تا هر دو طرف مقایسه یکسان نرمال بشن و «کتاب» با «كتاب» یکی دیده بشه.

const ZWNJ = '\u200C';

export function normalizeSearchText(s) {
  return String(s || '')
    .replace(/ك/g, 'ک')
    .replace(/ي/g, 'ی')
    .replace(/ة/g, 'ه')
    .replace(new RegExp(ZWNJ, 'g'), '')
    .replace(/[۰-۹]/g, (d) => '0123456789'['۰۱۲۳۴۵۶۷۸۹'.indexOf(d)])
    .replace(/[٠-٩]/g, (d) => '0123456789'['٠١٢٣٤٥٦٧٨٩'.indexOf(d)])
    .toLowerCase();
}

// همون جایگزینی‌های بالا ولی به‌صورت REPLACE()های تودرتوی SQL، تا مستقیم روی ستون دیتابیس اعمال بشه.
export function normalizeSql(columnExpr) {
  const pairs = [
    ['ك', 'ک'], ['ي', 'ی'], ['ة', 'ه'], [ZWNJ, ''],
    ['۰', '0'], ['۱', '1'], ['۲', '2'], ['۳', '3'], ['۴', '4'],
    ['۵', '5'], ['۶', '6'], ['۷', '7'], ['۸', '8'], ['۹', '9'],
    ['٠', '0'], ['١', '1'], ['٢', '2'], ['٣', '3'], ['٤', '4'],
    ['٥', '5'], ['٦', '6'], ['٧', '7'], ['٨', '8'], ['٩', '9'],
  ];
  let out = columnExpr;
  for (const [from, to] of pairs) {
    out = `REPLACE(${out}, '${from}', '${to}')`;
  }
  return `LOWER(${out})`;
}
